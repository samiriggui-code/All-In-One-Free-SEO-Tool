import PDFDocument from "pdfkit";
import type { Client, Invoice } from "@/db/schema";
import { getSetting } from "@/lib/settings-store";
import { invoiceTotals, formatMoney, lineAmount } from "@/lib/invoice-utils";

/**
 * The invoice as a PDF, in the workspace's language.
 *
 * Shared by the app's own download and the client portal, so the client
 * gets exactly the document the agency sees.
 */

const LABELS = {
  en: {
    title: "Invoice",
    invoice: "INVOICE",
    billTo: "BILL TO",
    issued: "ISSUED",
    due: "DUE",
    description: "DESCRIPTION",
    qty: "QTY",
    rate: "RATE",
    amount: "AMOUNT",
    subtotal: "Subtotal",
    tax: (pct: string) => `Tax (${pct}%)`,
    total: "Total",
    notes: "NOTES",
    paid: "PAID",
    void: "VOID",
    thanks: (brand: string) => `Thank you for your business · ${brand}`,
    generated: (when: string) => `Generated by SEO tool · ${when}`,
  },
  fr: {
    title: "Facture",
    invoice: "FACTURE",
    billTo: "FACTURÉ À",
    issued: "ÉMISE LE",
    due: "ÉCHÉANCE",
    description: "DÉSIGNATION",
    qty: "QTÉ",
    rate: "PRIX UNIT.",
    amount: "MONTANT",
    subtotal: "Total HT",
    tax: (pct: string) => `TVA (${pct.replace(".", ",")} %)`,
    total: "Total TTC",
    notes: "NOTES",
    paid: "PAYÉE",
    void: "ANNULÉE",
    thanks: (brand: string) => `Merci de votre confiance · ${brand}`,
    generated: (when: string) => `Générée par SEO tool · ${when}`,
  },
};

export type InvoiceLocale = keyof typeof LABELS;

export async function generateInvoicePdf(
  invoice: Invoice,
  client: Pick<Client, "name" | "url"> | undefined,
  locale: string,
): Promise<Buffer> {
  const lang: InvoiceLocale = locale === "fr" ? "fr" : "en";
  const L = LABELS[lang];
  const tag = lang === "fr" ? "fr-FR" : "en-US";
  // pdfkit's standard fonts have no narrow no-break space, which French
  // number formatting uses as its thousands separator.
  const money = (n: number, currency: string) =>
    formatMoney(n, currency, tag).replace(/[\u202f\u00a0]/g, " ");
  const date = (d: Date) => d.toLocaleDateString(tag);

  const brandName = await getSetting<string>("brand.name");
  const brandColor = await getSetting<string>("brand.color");
  const brandLogo = await getSetting<string>("brand.logo_data_url");
  const brandTagline = await getSetting<string>("brand.tagline");
  const brandWebsite = await getSetting<string>("brand.website");
  const brandEmail = await getSetting<string>("brand.email");
  const brandPhone = await getSetting<string>("brand.phone");
  const brandFooterText = await getSetting<string>("brand.footer_text");

  const accent =
    brandColor && /^#[0-9a-f]{6}$/i.test(brandColor)
      ? brandColor
      : "#6d49d6";

  const ink = "#0f1117";
  const mute = "#5b6173";
  const rule = "#dde0e7";

  const { subtotal, tax, total } = invoiceTotals(invoice.items, invoice.taxRate);

  const buffers: Buffer[] = [];
  // Tighter margins + auto-pagination disabled. We size every section
  // so a normal invoice (1-15 line items + tax + notes) fits on a
  // single A4 page. Wider invoices fall back to a second page
  // gracefully but the common case is one page.
  const doc = new PDFDocument({
    size: "A4",
    margins: { top: 40, bottom: 40, left: 40, right: 40 },
    info: {
      Title: `${L.title} ${invoice.invoiceNumber}`,
      Author: brandName ?? "SEO Tool",
    },
  });

  doc.on("data", (chunk: Buffer) => buffers.push(chunk));
  const finished = new Promise<Buffer>((resolve) => {
    doc.on("end", () => resolve(Buffer.concat(buffers)));
  });

  // Header: logo + brand name
  let logoBuffer: Buffer | null = null;
  if (brandLogo) {
    const m = brandLogo.match(/^data:(image\/[a-zA-Z+]+);base64,(.+)$/);
    if (m && (m[1] === "image/png" || m[1] === "image/jpeg")) {
      try {
        logoBuffer = Buffer.from(m[2], "base64");
      } catch {
        logoBuffer = null;
      }
    }
  }
  // Layout coordinates. Everything below is positioned explicitly so
  // the entire invoice fits on one A4 page for the common case
  // (≤15 line items + notes + tax).
  const LEFT = 40;
  const RIGHT = 555; // 595 - 40
  const COL_BILL_X = LEFT;
  const COL_META_X = 380;
  const TABLE_QTY_X = 340;
  const TABLE_RATE_X = 400;
  const TABLE_AMT_X = 470;

  // Header band: logo (left) + brand name (right). Fixed height 60px.
  const HEADER_HEIGHT = 60;
  if (logoBuffer) {
    try {
      doc.image(logoBuffer, LEFT, 40, { fit: [110, 36] });
    } catch {
      /* ignore */
    }
  }
  if (brandName) {
    doc
      .fontSize(11)
      .fillColor(ink)
      .font("Helvetica-Bold")
      .text(brandName, LEFT + 160, 42, {
        align: "right",
        width: RIGHT - LEFT - 160,
      });
    // Stack of small contact lines underneath. Each line is conditional
    // — only what the user actually filled in shows.
    const contactBits = [brandTagline, brandEmail, brandPhone, brandWebsite]
      .filter((s): s is string => Boolean(s))
      .slice(0, 3);
    if (contactBits.length > 0) {
      doc
        .fontSize(8.5)
        .fillColor(mute)
        .font("Helvetica")
        .text(contactBits.join(" · "), LEFT + 160, 58, {
          align: "right",
          width: RIGHT - LEFT - 160,
        });
    }
  }

  // INVOICE title row — moderate jump, not the doc.moveDown(3) of before
  doc
    .fontSize(24)
    .fillColor(accent)
    .font("Helvetica-Bold")
    .text(L.invoice, LEFT, 40 + HEADER_HEIGHT + 12);
  doc
    .fontSize(11)
    .fillColor(ink)
    .font("Helvetica")
    .text(invoice.invoiceNumber, LEFT, 40 + HEADER_HEIGHT + 42);

  // Two-column meta block: Bill to / Issue/Due
  const metaTop = 40 + HEADER_HEIGHT + 72;
  doc
    .fontSize(9)
    .fillColor(mute)
    .font("Helvetica-Bold")
    .text(L.billTo, COL_BILL_X, metaTop, { characterSpacing: 1.5 });
  doc
    .fontSize(11)
    .fillColor(ink)
    .font("Helvetica-Bold")
    .text(client?.name ?? "—", COL_BILL_X, metaTop + 13);
  if (client?.url) {
    doc
      .font("Helvetica")
      .fontSize(9)
      .fillColor(mute)
      .text(client.url, COL_BILL_X, metaTop + 28);
  }

  doc
    .fontSize(9)
    .fillColor(mute)
    .font("Helvetica-Bold")
    .text(L.issued, COL_META_X, metaTop, { characterSpacing: 1.5 });
  doc
    .font("Helvetica")
    .fontSize(10)
    .fillColor(ink)
    .text(date(invoice.issueDate), COL_META_X, metaTop + 13);

  if (invoice.dueDate) {
    doc
      .fontSize(9)
      .fillColor(mute)
      .font("Helvetica-Bold")
      .text(L.due, COL_META_X, metaTop + 30, { characterSpacing: 1.5 });
    doc
      .font("Helvetica")
      .fontSize(10)
      .fillColor(ink)
      .text(date(invoice.dueDate), COL_META_X, metaTop + 43);
  }

  // Line items table — anchored 60px below the meta block, regardless
  // of how many lines the meta produced. Saves the runaway moveDown(5).
  const tableTop = metaTop + 64;
  doc
    .strokeColor(rule)
    .lineWidth(0.5)
    .moveTo(LEFT, tableTop - 6)
    .lineTo(RIGHT, tableTop - 6)
    .stroke();

  doc.fontSize(8).fillColor(mute).font("Helvetica-Bold");
  doc.text(L.description, LEFT, tableTop, { characterSpacing: 1 });
  doc.text(L.qty, TABLE_QTY_X, tableTop, {
    width: 50,
    align: "right",
    characterSpacing: 1,
  });
  doc.text(L.rate, TABLE_RATE_X, tableTop, {
    width: 60,
    align: "right",
    characterSpacing: 1,
  });
  doc.text(L.amount, TABLE_AMT_X, tableTop, {
    width: 85,
    align: "right",
    characterSpacing: 1,
  });

  doc
    .strokeColor(rule)
    .lineWidth(0.5)
    .moveTo(LEFT, tableTop + 12)
    .lineTo(RIGHT, tableTop + 12)
    .stroke();

  // Lowest point content may reach, keeping room for the footer line.
  const BOTTOM = doc.page.height - 60;
  let y = tableTop + 18;
  /** Starts a new page when the next block would run past the bottom. */
  const room = (height: number) => {
    if (y + height <= BOTTOM) return;
    doc.addPage();
    y = 40;
  };

  // Line item row height: 16px (was 22). Comfortable but compact.
  doc.font("Helvetica").fillColor(ink).fontSize(10);
  for (const item of invoice.items) {
    const rowHeight = Math.max(16, doc.heightOfString(item.description, { width: 290 }) + 4);
    room(rowHeight);
    doc.font("Helvetica").fillColor(ink).fontSize(10);
    doc.text(item.description, LEFT, y, { width: 290 });
    doc.text(String(item.quantity), TABLE_QTY_X, y, {
      width: 50,
      align: "right",
    });
    doc.text(money(item.rate, invoice.currency), TABLE_RATE_X, y, {
      width: 60,
      align: "right",
    });
    doc.text(money(lineAmount(item), invoice.currency), TABLE_AMT_X, y, {
      width: 85,
      align: "right",
    });
    // A long description wraps inside its column: the next row starts
    // below it, not on top of its second line.
    y += rowHeight;
  }

  // Subtotal, tax and total stay together on one page.
  room(70);

  doc
    .strokeColor(rule)
    .lineWidth(0.5)
    .moveTo(TABLE_QTY_X, y + 2)
    .lineTo(RIGHT, y + 2)
    .stroke();

  y += 10;
  doc.fontSize(10).fillColor(mute).font("Helvetica").text(L.subtotal, TABLE_QTY_X, y, {
    width: 120,
    align: "right",
  });
  doc.fillColor(ink).text(money(subtotal, invoice.currency), TABLE_AMT_X, y, {
    width: 85,
    align: "right",
  });

  if (invoice.taxRate > 0) {
    y += 16;
    doc.fillColor(mute).text(
      L.tax((invoice.taxRate / 100).toFixed(2)),
      TABLE_QTY_X,
      y,
      { width: 120, align: "right" },
    );
    doc.fillColor(ink).text(money(tax, invoice.currency), TABLE_AMT_X, y, {
      width: 85,
      align: "right",
    });
  }

  y += 20;
  doc
    .font("Helvetica-Bold")
    .fontSize(12)
    .fillColor(accent)
    .text(L.total, TABLE_QTY_X, y, { width: 120, align: "right" });
  doc.text(money(total, invoice.currency), TABLE_AMT_X, y, {
    width: 85,
    align: "right",
  });

  // Notes — compact gap, not the 60px of before
  if (invoice.notes) {
    y += 40;
    doc.font("Helvetica").fontSize(10);
    room(14 + doc.heightOfString(invoice.notes, { width: RIGHT - LEFT }));
    doc.font("Helvetica-Bold").fontSize(9).fillColor(mute);
    doc.text(L.notes, LEFT, y, { characterSpacing: 1.5 });
    doc.font("Helvetica").fillColor(ink).fontSize(10).text(
      invoice.notes,
      LEFT,
      y + 14,
      { width: RIGHT - LEFT },
    );
  }

  // Status watermark
  if (invoice.status === "paid") {
    doc.save();
    doc.fontSize(60).fillColor("#0f9460").opacity(0.15).rotate(-25, {
      origin: [300, 400],
    });
    doc.text(L.paid, 200, 380, { align: "center", width: 200 });
    doc.restore();
  } else if (invoice.status === "void") {
    doc.save();
    doc.fontSize(60).fillColor(mute).opacity(0.15).rotate(-25, {
      origin: [300, 400],
    });
    doc.text(L.void, 200, 380, { align: "center", width: 200 });
    doc.restore();
  }

  // Footer — uses brand.footer_text when set (registration info,
  // tagline, address); falls back to a generic line otherwise.
  // It sits inside the bottom margin, which pdfkit would otherwise
  // answer with a page holding nothing but this line.
  doc.page.margins.bottom = 0;
  doc
    .fillColor(mute)
    .font("Helvetica-Oblique")
    .fontSize(8)
    .text(
      brandFooterText ??
        (brandName
          ? L.thanks(brandName)
          : L.generated(date(new Date()))),
      LEFT,
      doc.page.height - 30,
      { align: "center", width: doc.page.width - LEFT * 2 },
    );

  doc.end();
  const pdf = await finished;
  return pdf;
}
